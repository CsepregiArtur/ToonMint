-- Consimțământul la termeni, ștergerea contului și dovada confirmării la checkout.
--
-- 1. `terms_version` + `terms_accepted_at` = dovada acceptării termenilor la
--    înregistrare (GDPR art. 7(1) — sarcina probei este a operatorului).
-- 2. `deleted_at` marchează contul anonimizat, nu șters fizic: documentele
--    contabile (credit_transactions) trebuie păstrate 10 ani (Legea 82/1991).
-- 3. `purchase_acknowledgements` = dovada că utilizatorul a solicitat livrarea
--    imediată și a acceptat pierderea dreptului de retragere
--    (OUG 34/2014 art. 16 lit. m).

ALTER TABLE users ADD COLUMN terms_version VARCHAR(20);
ALTER TABLE users ADD COLUMN terms_accepted_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN deleted_at TIMESTAMP WITH TIME ZONE;

CREATE INDEX idx_users_deleted_at ON users (deleted_at);

CREATE TABLE purchase_acknowledgements (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT       NOT NULL REFERENCES users (id),
    product_id         VARCHAR(100) NOT NULL,
    kind               VARCHAR(20),
    terms_version      VARCHAR(20),
    immediate_delivery BOOLEAN      NOT NULL DEFAULT TRUE,
    withdrawal_waived  BOOLEAN      NOT NULL DEFAULT TRUE,
    client_ip          VARCHAR(64),
    accepted_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_purchase_ack_user_product
    ON purchase_acknowledgements (user_id, product_id, accepted_at DESC);
