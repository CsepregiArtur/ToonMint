-- Registru financiar (bookkeeping): încasări din RevenueCat și cheltuieli
-- (cost AI per generare, hosting, marketing etc.). Sumele sunt păstrate în moneda
-- înregistrată, iar `fx_rate` le convertește în moneda de raportare la citire.
--
-- Indexul unic face idempotență posibilă: un job poate produce o singură
-- intrare AI_GENERATION, iar un eveniment RevenueCat o singură intrare SALE.

CREATE TABLE finance_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind           VARCHAR(16)    NOT NULL,
    category       VARCHAR(32)    NOT NULL,
    amount         NUMERIC(14, 4) NOT NULL,
    currency       VARCHAR(3)     NOT NULL,
    fx_rate        NUMERIC(14, 6) NOT NULL DEFAULT 1,
    source         VARCHAR(16)    NOT NULL,
    reference_type VARCHAR(24),
    reference_key  VARCHAR(255),
    product_id     VARCHAR(100),
    description    VARCHAR(255),
    occurred_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX ux_finance_entries_reference
    ON finance_entries (source, reference_type, reference_key, category);
CREATE INDEX idx_finance_entries_occurred ON finance_entries (occurred_at DESC);
CREATE INDEX idx_finance_entries_category_occurred ON finance_entries (category, occurred_at DESC);
