-- Tokenuri de refresh, ca sesiunea să nu expire odată cu JWT-ul de 24 de ore.
--
-- 1. Tokenul propriu-zis nu se stochează: rămâne doar SHA-256 al lui, deci o
--    scurgere a bazei nu permite reconstruirea unei sesiuni valide.
-- 2. Fiecare token se folosește o singură dată. La refresh este revocat și
--    înlocuit cu altul, iar refolosirea unui token deja revocat anulează toate
--    sesiunile utilizatorului (semn că tokenul a fost copiat).

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    token_hash VARCHAR(64)  NOT NULL UNIQUE,
    issued_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE
);

-- Căutarea din refresh și revocarea în bloc la ștergerea contului.
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
-- Curățarea periodică a tokenurilor expirate.
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);
