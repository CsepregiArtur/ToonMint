-- ToonMint initial schema.
-- Image bytes are never persisted: only job metadata and credit accounting live here.

CREATE TABLE users (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id              UUID         NOT NULL UNIQUE,
    email                  VARCHAR(255) NOT NULL UNIQUE,
    password_hash          VARCHAR(255) NOT NULL,
    display_name           VARCHAR(100),
    credit_balance         INTEGER      NOT NULL DEFAULT 0,
    subscription_type      VARCHAR(20)  NOT NULL DEFAULT 'FREE',
    subscription_expires_at TIMESTAMP WITH TIME ZONE,
    role                   VARCHAR(20)  NOT NULL DEFAULT 'USER',
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE jobs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id        UUID        NOT NULL UNIQUE,
    user_id          BIGINT      NOT NULL REFERENCES users (id),
    style_id         VARCHAR(50) NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    credits_consumed INTEGER     NOT NULL DEFAULT 1,
    input_mime_type  VARCHAR(100),
    input_size_bytes BIGINT,
    error_message    TEXT,
    attempts         INTEGER     NOT NULL DEFAULT 0,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    started_at       TIMESTAMP WITH TIME ZONE,
    completed_at     TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_jobs_user_status_created ON jobs (user_id, status, created_at DESC);
CREATE INDEX idx_jobs_created_at ON jobs (created_at);

CREATE TABLE credit_transactions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL REFERENCES users (id),
    amount            INTEGER      NOT NULL,
    type              VARCHAR(24)  NOT NULL,
    reference_job_id  BIGINT       REFERENCES jobs (id),
    provider          VARCHAR(32),
    external_reference VARCHAR(255),
    description       VARCHAR(255),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_credit_transactions_user_created ON credit_transactions (user_id, created_at DESC);
CREATE UNIQUE INDEX ux_credit_transactions_external_ref
    ON credit_transactions (external_reference);

CREATE TABLE subscription_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR(255) NOT NULL UNIQUE,
    user_id      BIGINT       REFERENCES users (id),
    event_type   VARCHAR(50)  NOT NULL,
    product_id   VARCHAR(100),
    app_user_id  VARCHAR(255),
    status       VARCHAR(20)  NOT NULL DEFAULT 'IGNORED',
    message      VARCHAR(500),
    payload      TEXT,
    received_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_subscription_events_user ON subscription_events (user_id);
CREATE INDEX idx_subscription_events_received ON subscription_events (received_at DESC);

CREATE TABLE email_messages (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sent_by_user_id   BIGINT       REFERENCES users (id),
    recipient_count   INTEGER      NOT NULL,
    subject           VARCHAR(255) NOT NULL,
    body              TEXT         NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    error_message     VARCHAR(500),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);
