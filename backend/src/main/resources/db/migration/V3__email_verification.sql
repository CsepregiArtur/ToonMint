-- Verificarea adresei de email și resetarea parolei prin cod OTP.
-- Codurile nu se stochează niciodată în clar: doar hash-ul BCrypt al acestora.

ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN email_verified_at TIMESTAMP WITH TIME ZONE;

-- Conturile existente rămân neverificate (login blocat până la confirmare) și își
-- pot confirma adresa prin /api/auth/resend-verification sau prin resetarea parolei.
-- Pentru o migrare fără blocaje, rulează manual:
--   UPDATE users SET email_verified = TRUE, email_verified_at = NOW() WHERE email_verified = FALSE;

CREATE TABLE verification_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    purpose     VARCHAR(32)  NOT NULL,
    code_hash   VARCHAR(255) NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts    INTEGER      NOT NULL DEFAULT 0,
    consumed_at TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_verification_codes_user_purpose
    ON verification_codes (user_id, purpose, created_at DESC);
