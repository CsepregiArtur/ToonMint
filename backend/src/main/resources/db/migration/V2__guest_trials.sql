-- Trial gratuit: o singură generare per adresă de email, fără cont.
-- Joburile de trial nu au utilizator (user_id devine opțional) și consumă 0 credite.

ALTER TABLE jobs ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE jobs ADD COLUMN guest_email VARCHAR(255);
ALTER TABLE jobs ADD COLUMN trial BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX idx_jobs_guest_email ON jobs (guest_email);

CREATE TABLE guest_trials (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL UNIQUE,
    job_id     BIGINT       REFERENCES jobs (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);
